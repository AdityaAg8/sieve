"use client";

import { ErrorNote } from "@/components/shell/ErrorNote";
import {
  ablationsOf,
  ensembleAgreementOf,
  headlineOf,
  holdoutLogOf,
  isProvisional,
  labelAuditOf,
  minimalPairsOf,
  perConcealmentOf,
  perTierOf,
  tablesOf,
} from "@/lib/bench";
import { footerDestinations } from "@/lib/links";
import { useBench } from "@/lib/queries";

import { AblationTable } from "./AblationTable";
import { Agreement } from "./Agreement";
import { ConcealmentChart } from "./ConcealmentChart";
import { ConfusionMatrix } from "./ConfusionMatrix";
import { HeadlineTable } from "./HeadlineTable";
import { HoldoutLog } from "./HoldoutLog";
import { HumanReference } from "./HumanReference";
import { MinimalPairs } from "./MinimalPairs";
import { TierChart } from "./TierChart";

export function BenchmarkScreen() {
  const bench = useBench();
  // A fetch that failed is not the same as a benchmark that has not been run. Saying
  // "numbers appear after the first make bench" during an outage is a false explanation.
  const unreachable = bench.isError;
  const provisional = !unreachable && isProvisional(bench.data);
  // Each panel reads its own results file's keys (training plan I5); a missing file leaves its
  // panel with dashes or an empty note, never a placeholder number.
  const headline = headlineOf(bench.data);
  const tables = tablesOf(bench.data);
  const minimalPairs = minimalPairsOf(bench.data);
  const audit = labelAuditOf(bench.data);

  return (
    <>
      <section className="band-hero pattern-gutters">
        <div className="wrap flex flex-col gap-4">
          <p className="eyebrow-rail with-mark">Benchmark</p>
          <h1 className="t-h2 text-ink-0">SieveBench, in full</h1>
          <p className="t-lead text-ink-1 max-w-[68ch]">
            Everything here is regenerated by <code className="t-mono">make bench</code> from
            committed predictions. Nothing on this page is typed in by hand, which is also why a
            number that has not been measured shows as a dash rather than a placeholder.
          </p>

          {unreachable ? (
            <ErrorNote
              title="The published numbers could not be loaded."
              detail="Nothing below has been measured in this session; the dashes are missing data, not results."
              onRetry={() => void bench.refetch()}
            />
          ) : provisional ? (
            <p
              data-testid="provisional-notice"
              className="t-body text-ink-1 border-line-2 border-l-2 pl-4"
            >
              Numbers appear after the first <code className="t-mono">make bench</code>.
            </p>
          ) : (
            <dl className="t-ui text-ink-2 flex flex-wrap gap-2">
              <div className="border-line-0 bg-bg-1 rounded-2 flex items-center gap-2 border px-2.5 py-1">
                <dt>Dataset</dt>
                <dd className="t-mono text-ink-1">{bench.data?.dataset_version}</dd>
              </div>
              <div className="border-line-0 bg-bg-1 rounded-2 flex items-center gap-2 border px-2.5 py-1">
                <dt>Model</dt>
                <dd className="t-mono text-ink-1">{bench.data?.model_version}</dd>
              </div>
              <div className="border-line-0 bg-bg-1 rounded-2 flex items-center gap-2 border px-2.5 py-1">
                <dt>Generated</dt>
                <dd className="t-mono text-ink-1">{bench.data?.generated_at}</dd>
              </div>
            </dl>
          )}
        </div>
      </section>

      <div className="wrap flex min-w-0 flex-col gap-10 pb-20">
        <HeadlineTable headline={headline} />
        <AblationTable rows={ablationsOf(bench.data)} />
        <TierChart rows={perTierOf(bench.data)} />
        <ConcealmentChart rows={perConcealmentOf(bench.data)} />
        <ConfusionMatrix matrix={tables.confusion} />
        <Agreement audit={audit} ensemble={ensembleAgreementOf(bench.data)} />
        <MinimalPairs rows={minimalPairs.rows} deferred={minimalPairs.deferred} />
        <HumanReference audit={audit} />
        <HoldoutLog rows={holdoutLogOf(bench.data)} />

        <section aria-labelledby="artefacts" className="border-line-0 flex min-w-0 flex-col gap-4 border-t pt-10">
          <h2 id="artefacts" className="t-h3 text-ink-0">
            Artefacts
          </h2>
          <ul className="t-ui flex flex-wrap gap-x-6 gap-y-2">
            {footerDestinations.map((destination) => (
              <li key={destination.label}>
                {destination.href ? (
                  <a
                    href={destination.href}
                    target="_blank"
                    rel="noreferrer noopener"
                    className="u-interactive text-ink-1 hover:text-ink-0 border-line-2 inline-flex min-h-6 items-end border-b pb-0.5"
                  >
                    {destination.label}
                  </a>
                ) : (
                  <span className="text-ink-3">
                    {destination.label} <span className="text-ink-2">— not published yet</span>
                  </span>
                )}
              </li>
            ))}
          </ul>
        </section>
      </div>
    </>
  );
}
